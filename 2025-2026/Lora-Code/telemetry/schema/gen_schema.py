#!/usr/bin/env python3
"""Generate the firmware header (and the C cross-check filler) from telemetry_schema.yaml.

    py gen_schema.py            # write the generated files
    py gen_schema.py --check    # exit 1 if a generated file is out of date

Outputs (both committed):
    LoRa_board/Core/Inc/telemetry_schema.h   packed structs, _Static_asserts, #defines
    telemetry/tests/host/xcheck_fill.c       fills every field with a known value (cross-check)
"""
import argparse
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
LORA = os.path.normpath(os.path.join(HERE, "..", ".."))
YAML_PATH = os.path.join(HERE, "telemetry_schema.yaml")
HEADER_PATH = os.path.join(LORA, "LoRa_board", "Core", "Inc", "telemetry_schema.h")
XCHECK_PATH = os.path.join(LORA, "telemetry", "tests", "host", "xcheck_fill.c")

CTYPE = {"u8": "uint8_t", "i8": "int8_t", "u16": "uint16_t", "i16": "int16_t",
         "u32": "uint32_t", "i32": "int32_t"}
SIZE = {"u8": 1, "i8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4}
ARRAY = re.compile(r"^u8\[(\d+)\]$")


def load():
    with open(YAML_PATH, encoding="utf-8") as f:
        return yaml.safe_load(f)


def field_size(f):
    t = f["type"]
    if t == "struct":
        return f["count"] * f["size"]
    m = ARRAY.match(t)
    if m:
        return int(m.group(1))
    return SIZE[t]


def ident(s):
    return re.sub(r"[^A-Za-z0-9]", "_", str(s)).upper()


def check_layout(where, fields, total):
    """Fields must be in offset order, non-overlapping and inside `total` bytes."""
    end = 0
    for f in fields:
        if f["pos"] < end:
            raise SystemExit(f"{where}.{f['name']}: offset {f["pos"]} overlaps the previous field")
        end = f["pos"] + field_size(f)
    if end > total:
        raise SystemExit(f"{where}: fields end at {end}, past {total} bytes")


def emit_struct(lines, cname, fields, total, sub_structs):
    """Packed struct with explicit reserved padding so every offset matches the YAML."""
    check_layout(cname, fields, total)
    body, pos = [], 0
    for f in fields:
        if f["pos"] > pos:
            body.append(f"    uint8_t _rsv{pos}[{f["pos"] - pos}];")
        t = f["type"]
        if t == "struct":
            body.append(f"    ts_{f['c_name']}_t {f['name']}[{f['count']}];")
        elif ARRAY.match(t):
            body.append(f"    uint8_t {f['name']}[{field_size(f)}];")
        else:
            body.append(f"    {CTYPE[t]} {f['name']};")
        pos = f["pos"] + field_size(f)
    if pos < total:
        body.append(f"    uint8_t _rsv{pos}[{total - pos}];")
    lines.append("typedef struct __attribute__((packed)) {")
    lines += body
    lines.append(f"}} ts_{cname}_t;")
    lines.append(f"_Static_assert(sizeof(ts_{cname}_t) == {total}, \"ts_{cname}_t size\");")
    for f in fields:
        lines.append(f"_Static_assert(offsetof(ts_{cname}_t, {f['name']}) == {f["pos"]}, "
                     f"\"ts_{cname}_t.{f['name']} offset\");")
    lines.append("")


def gen_header(s):
    L = ["/* GENERATED by telemetry/schema/gen_schema.py from telemetry_schema.yaml. DO NOT EDIT.",
         " * Regenerate: py gen_schema.py   Check: py gen_schema.py --check */",
         "#ifndef TELEMETRY_SCHEMA_H", "#define TELEMETRY_SCHEMA_H", "",
         "#include <stddef.h>", "#include <stdint.h>", ""]
    pk, tr, cmd = s["packet"], s["transport"], s["command"]
    L += [f"#define TS_SCHEMA_VERSION      {s['version']}",
          f"#define TS_FW_VERSION          0x{s['firmware_version']:04X}u",
          f"#define TS_CRC_POLY            0x{s['crc']['poly']:04X}u",
          f"#define TS_CRC_INIT            0x{s['crc']['init']:04X}u",
          f"#define TS_CRC_CHECK           0x{s['crc']['check']['value']:04X}u  /* \"123456789\" */",
          "",
          f"#define TS_PKT_SIZE            {pk['size']}",
          f"#define TS_PKT_VERSION         {pk['version']}",
          f"#define TS_SYNC0               0x{pk['sync'][0]:02X}u",
          f"#define TS_SYNC1               0x{pk['sync'][1]:02X}u",
          f"#define TS_PAYLOAD_OFF         {pk['payload_off']}",
          f"#define TS_PAYLOAD_SIZE        {pk['payload_size']}",
          f"#define TS_CRC_OFF             {pk['crc_off']}",
          "",
          "/* Transport (measured; see lora_framing_results.md) */"]
    for i, b in enumerate(tr["header_car_to_pc"]):
        L.append(f"#define TS_HDR_TO_PC_{i}         0x{b:02X}u")
    for i, b in enumerate(tr["header_pc_to_car"]):
        L.append(f"#define TS_HDR_TO_CAR_{i}        0x{b:02X}u")
    for k in ("write_period_ms", "packets_per_write", "write_size", "min_write_gap_ms", "max_write_size",
              "command_delay_ms", "pc_min_write_gap_ms"):
        L.append(f"#define TS_{k.upper():22s} {tr[k]}")
    L += ["", "/* Packet types */"]
    for name, v in s["types"].items():
        L.append(f"#define TS_TYPE_{name:16s} {v}")
    L += ["", "/* Command packet */",
          f"#define TS_CMD_SIZE            {cmd['size']}",
          f"#define TS_CMD_VER_TYPE        0x{cmd['ver_type']:02X}u",
          f"#define TS_CMD_KEY0            0x{cmd['key'][0]:02X}u",
          f"#define TS_CMD_KEY1            0x{cmd['key'][1]:02X}u",
          f"#define TS_CMD_ARGS_OFF        {cmd['args_off']}",
          f"#define TS_CMD_ARGS_SIZE       {cmd['args_size']}",
          f"#define TS_CMD_CRC_OFF         {cmd['crc_off']}"]
    for name, c in cmd["codes"].items():
        L.append(f"#define TS_CMD_{name:16s} 0x{c['code']:02X}u")
    L += ["", "/* Status codes (command acknowledgements) */"]
    for v, name in s["status_codes"].items():
        L.append(f"#define TS_ST_{name:16s} {v}u")
    L += ["", "/* Event codes */"]
    for v, e in s["event_codes"].items():
        L.append(f"#define TS_EVT_{e['name']:20s} {v}u")
    L += ["", "/* FAST valid bits (bit number, mask, timeout) */"]
    for b in s["valid_bits"]:
        n = ident(b["name"])
        L.append(f"#define TS_VB_{n:14s} {b['bit']}")
    L.append("#define TS_VALID_TIMEOUTS_MS { " + ", ".join(str(b["timeout_ms"]) for b in s["valid_bits"]) + " }")
    L.append(f"#define TS_N_VALID_BITS        {len(s['valid_bits'])}")
    L += ["", "/* FAST status bits */"]
    for b in s["status_bits"]:
        L.append(f"#define TS_STATUS_{ident(b['name']):16s} (1u << {b['bit']})")
    L += ["", "/* DIAG build option bits */"]
    for b in s["build_opt_bits"]:
        L.append(f"#define TS_OPT_{ident(b['name']):16s} (1u << {b['bit']})")
    L += ["", "/* Bamocar registers */"]
    regs = s["bamocar_registers"]
    for r, d in regs.items():
        L.append(f"#define TS_REG_{d['name']:16s} 0x{r:02X}u")
    wb = [r for r, d in regs.items() if d.get("blocked")]
    rb = [r for r, d in regs.items() if d.get("read_blocked")]
    L.append("#define TS_WRITE_BLOCKED_REGS  { " + ", ".join(f"0x{r:02X}u" for r in wb) + " }")
    L.append(f"#define TS_N_WRITE_BLOCKED     {len(wb)}")
    L.append("#define TS_READ_BLOCKED_REGS   { " + ", ".join(f"0x{r:02X}u" for r in rb) + " }")
    L.append(f"#define TS_N_READ_BLOCKED      {len(rb)}")
    L += [""]

    # --- structs
    L.append("/* ---------------------------------------------------------------- structs */")
    hdr_fields = pk["fields"]
    emit_struct(L, "pkt_hdr", hdr_fields, pk["payload_off"], [])
    for name, p in s["payloads"].items():
        for f in p["fields"]:
            if f["type"] == "struct":
                emit_struct(L, f["c_name"], f["fields"], f["size"], [])
        emit_struct(L, p["c_name"], p["fields"], pk["payload_size"], [])
    L += ["typedef struct __attribute__((packed)) {",
          "    ts_pkt_hdr_t hdr;",
          "    union {",
          f"        uint8_t raw[{pk['payload_size']}];"]
    for name, p in s["payloads"].items():
        L.append(f"        ts_{p['c_name']}_t {p['c_name']};")
    L += ["    } p;", "    uint16_t crc;", "} ts_packet_t;",
          f"_Static_assert(sizeof(ts_packet_t) == {pk['size']}, \"ts_packet_t size\");",
          f"_Static_assert(offsetof(ts_packet_t, crc) == {pk['crc_off']}, \"ts_packet_t crc offset\");", ""]
    # command + per-code args
    emit_struct(L, "cmd", cmd["fields"], cmd["size"], [])
    for name, c in cmd["codes"].items():
        if c["args"]:
            emit_struct(L, f"args_{name.lower()}", c["args"], cmd["args_size"], [])
    L += ["#endif /* TELEMETRY_SCHEMA_H */", ""]
    return "\n".join(L)


# ------------------------------------------------------------------ cross-check filler
def xv_c(a, b):
    return f"xv({a}u, {b}u)"


def gen_xcheck(s):
    """C code that fills every field of every payload with xv(type*64 + field index, element).
    tests/test_xcheck.py computes the same values from the YAML and compares."""
    L = ["/* GENERATED by telemetry/schema/gen_schema.py. DO NOT EDIT.",
         " * Fills every schema field with a known value; test_xcheck.py checks them in Python. */",
         "#include <string.h>", "#include \"telemetry_schema.h\"", "",
         "static uint32_t xv(uint32_t a, uint32_t b)",
         "{", "    return (a * 2654435761u) ^ (b * 40503u + 0x9E37u);", "}", ""]

    def fill(prefix, fields, a):
        out = []
        for fi, f in enumerate(fields):
            t = f["type"]
            key = a * 64 + fi
            if t == "struct":
                for j in range(f["count"]):
                    for sfi, sf in enumerate(f["fields"]):
                        out += fill_one(f"{prefix}{f['name']}[{j}].", sf, key * 32 + j * 8 + sfi)
            else:
                out += fill_one(prefix, f, key)
        return out

    def fill_one(prefix, f, key):
        t = f["type"]
        m = ARRAY.match(t)
        if m:
            return [f"    for (int k = 0; k < {m.group(1)}; k++) {prefix}{f['name']}[k] = "
                    f"(uint8_t)xv({key}u, 1000u + (uint32_t)k);"]
        return [f"    {prefix}{f['name']} = ({CTYPE[t]})xv({key}u, 0u);"]

    for name, p in s["payloads"].items():
        L.append(f"void xcheck_fill_{p['c_name']}(ts_{p['c_name']}_t *x)")
        L.append("{")
        L.append("    memset(x, 0, sizeof(*x));")
        L += fill("x->", p["fields"], p["type"])
        L += ["}", ""]
    for name, c in s["command"]["codes"].items():
        if c["args"]:
            L.append(f"void xcheck_fill_args_{name.lower()}(ts_args_{name.lower()}_t *x)")
            L.append("{")
            L.append("    memset(x, 0, sizeof(*x));")
            L += fill("x->", c["args"], 100 + c["code"])
            L += ["}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    s = load()
    outputs = {HEADER_PATH: gen_header(s), XCHECK_PATH: gen_xcheck(s)}
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if args.check:
            if old != text:
                stale.append(path)
        elif old != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(path, LORA)}")
        else:
            print(f"up to date: {os.path.relpath(path, LORA)}")
    if args.check:
        if stale:
            for p in stale:
                print(f"OUT OF DATE: {os.path.relpath(p, LORA)}  (run: py gen_schema.py)")
            sys.exit(1)
        print("gen_schema --check: generated files are up to date")


if __name__ == "__main__":
    main()
